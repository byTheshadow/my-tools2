// 教学夜的脚本。改台词、加一步，都只改这里。
//   say    进入这一步时澄姐说的话（一句一屏，点一下翻）
//   goal   { ev: 事件名, n: 次数 }；没有 goal 就是说完自动进下一步
//          事件名由玩法步骤发出：rice(捏好一个) / fish(鱼片放上) / serve(上菜成功) / discard(倒掉) / fail(失败)
//   task   左上角的小目标文字，{n} 会换成"已完成 / 需要"
//   allow  这一步放开什么：belt 传送带 / customers 客人自己来 / patience 耐心会掉 / timer 倒计时
//   spawn  'match' = 立刻来一位客人，点的正好是砧板上这份（没有就随机）
//   after  完成后澄姐的回应
//   fail   失败时澄姐的安慰（只说一次，不打断操作）
(function (SG) {
  SG.TUTORIAL = [
    {
      id: 'hello',
      say: [
        '（把围裙递过来）来得正好。今晚雨小，人不会太多。',
        '我是澄姐，这家店是我开的。',
        '先看一遍，再上手。做坏了算我的。',
      ],
    },
    {
      id: 'rice',
      say: [
        '第一步，捏饭团。按住屏幕，白圈会往里缩。',
        '缩进金色那圈就松手。缩过头饭团会碎，重捏一个就是了。',
      ],
      task: '捏好 2 个饭团　{n}',
      goal: { ev: 'rice', n: 2 },
      fail: '没事，手劲是练出来的。再来。',
      after: ['手挺稳。比我当年强。'],
    },
    {
      id: 'fish',
      say: [
        '传送带开了。鱼片一片一片过来。',
        '点一下，离中线最近的那片就落下来。',
        '落点要对准中线，鱼片才摆得正。',
      ],
      task: '把鱼片放上饭团　{n}',
      goal: { ev: 'fish', n: 1 },
      allow: { belt: true },
      fail: '歪了也无妨，鱼片捡起来还能再放。',
      after: ['就是这样。'],
    },
    {
      id: 'serve',
      say: [
        '客人来了。头顶那个气泡，是他点的东西。',
        '做的跟他要的一样，点他就行。送错了他会生气，但不会走。',
      ],
      task: '给客人上一份　{n}',
      goal: { ev: 'serve', n: 1 },
      allow: { belt: true },
      spawn: 'match',
      after: ['看见没，他笑了。深夜愿意进来的人，都不难伺候。'],
    },
    {
      id: 'discard',
      say: [
        '也会有做坏的，或者没人要的。',
        '别硬端出去。右下角那个桶，点一下倒掉，重做一个。',
        '随手捏一个试试——这回故意做坏也行。',
      ],
      task: '倒掉一份寿司　{n}',
      goal: { ev: 'discard', n: 1 },
      allow: { belt: true },
      after: ['倒掉不丢人。端出去的东西，得对得起客人。'],
    },
    {
      id: 'free',
      say: [
        '好了，剩下的时间你自己来。',
        '饭要捏得刚刚好，鱼要放得正正好。',
        '慢一点也没关系，夜还很长。',
      ],
      allow: { belt: true, customers: true, patience: true, timer: true },
    },
  ];

  // 教学夜结束时澄姐的话（按上菜份数挑一句）
  SG.TUTORIAL_END = [
    { min: 0, text: '第一晚能站下来就不错。明天正式开门。' },
    { min: 4, text: '像那么回事了。明天就交给你。' },
    { min: 8, text: '……你以前是不是干过这行？' },
  ];
})(window.SG = window.SG || {});